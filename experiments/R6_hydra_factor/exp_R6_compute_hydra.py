# exp_R6_compute_hydra.py
"""
exp_R6_compute_hydra.py
Assembles the literal numbers of the '\\textbf{Empirical validation.}' paragraph:
the Hydra acceleration factor tau_HAT / tau_ARF over the Delta_e sweep, and the
power-law prefactors/exponents (K_HAT, K_ARF, alpha_HAT, alpha_ARF).
Inputs : R6_hat_instrumented.parquet (tau_hat)  +  R2_instrumented_A_PHT_ARF.parquet (tau_arf).
Output : a small .tex snippet + console report. No figure.
"""
import numpy as np
import pandas as pd
from pathlib import Path

ROOT_DIR = Path(__file__).resolve().parent.parent.parent
R6 = ROOT_DIR / "results" / "R6_hydra_factor" / "data" / "R6_hat_instrumented.parquet"
R2 = ROOT_DIR / "results" / "R2_instrumented_blind_spot" / "data" / "R2_instrumented_A_PHT_ARF.parquet"
OUT = ROOT_DIR / "results" / "R6_hydra_factor" / "tables" / "exp_R6_hydra_empirical_validation.tex"
OUT.parent.mkdir(parents=True, exist_ok=True)

def powerlaw(series_mean):
    v = series_mean[(series_mean.index > 0) & (series_mean.values > 0)]
    c = np.polyfit(np.log(v.index.values), np.log(v.values), 1)
    return np.exp(c[1]), c[0]  # (prefactor K, exponent alpha)

hat = pd.read_parquet(R6).dropna(subset=['tau_hat'])
arf = pd.read_parquet(R2).dropna(subset=['tau_arf'])
# R2 stores boundary_shift; map to the same Delta_e transform if 'delta_e' absent
if 'delta_e' not in arf.columns:
    from scipy.stats import norm
    arf['delta_e'] = norm.cdf(arf['boundary_shift'] / np.sqrt(2)) - 0.5

hat_m = hat.groupby('delta_e')['tau_hat'].mean()
arf_m = arf.groupby('delta_e')['tau_arf'].mean()

merged = pd.concat([hat_m.rename('tau_hat'), arf_m.rename('tau_arf')], axis=1).dropna()
merged['hydra'] = merged['tau_hat'] / merged['tau_arf']

K_hat, a_hat = powerlaw(hat_m)
K_arf, a_arf = powerlaw(arf_m)

# Hydra endpoints near the magnitudes cited in the paper
def at(de):
    i = (merged.index.to_series() - de).abs().idxmin()
    return merged.loc[i, 'hydra'], i
h_lo, de_lo = at(0.14)
h_hi, de_hi = at(0.33)

report = (
    f"Hydra factor tau_HAT/tau_ARF: {h_lo:.1f}x at Delta_e={de_lo:.2f}  ->  {h_hi:.1f}x at Delta_e={de_hi:.2f}\n"
    f"HAT power law : tau_HAT ~ {K_hat:.1f} (Delta_e)^{a_hat:.2f}\n"
    f"ARF power law : tau_ARF ~ {K_arf:.1f} (Delta_e)^{a_arf:.2f}\n"
)
print(report)
print("[INFO] Extracted empirical parameters. Validation against published claims is deferred to tests/test_R6_hydra.py.")

with open(OUT, "w") as f:
    f.write("% Auto-generated by exp_R6_compute_hydra.py -- Extract of the empirical Hydra factors.\n")
    f.write(f"% Hydra: {h_lo:.1f}x (de={de_lo:.2f}) to {h_hi:.1f}x (de={de_hi:.2f}); "
            f"K_HAT={K_hat:.1f} a={a_hat:.2f}; K_ARF={K_arf:.1f} a={a_arf:.2f}\n")
print(f"[SUCCESS] snippet -> {OUT}")